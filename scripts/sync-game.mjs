import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { resolve } from 'node:path'
import ts from 'typescript'

// The Web app is the source of truth. Emit plain JS for the WeChat JS runtime
// and CommonJS for uniCloud so game rules cannot drift between platforms.
const root = resolve(import.meta.dirname, '..')
const targets = [
  { directory: 'apps/miniapp/common/game', module: ts.ModuleKind.ESNext },
  { directory: 'apps/miniapp/uniCloud-aliyun/cloudfunctions/common/miao-game', module: ts.ModuleKind.CommonJS },
]
let stale = false
for (const target of targets) {
  await mkdir(resolve(root, target.directory), { recursive: true })
  for (const name of ['data', 'engine']) {
    const source = (await readFile(resolve(root, `src/game/${name}.ts`), 'utf8')).replaceAll("'./data.ts'", "'./data.js'")
    const generated = '// Generated by npm run sync:game from src/game. Do not edit by hand.\n' + ts.transpileModule(source, {
      compilerOptions: { target: ts.ScriptTarget.ES2020, module: target.module, removeComments: false },
    }).outputText
    const destination = resolve(root, target.directory, `${name}.js`)
    const current = await readFile(destination, 'utf8').catch(() => '')
    if (current === generated) continue
    if (process.argv.includes('--check')) { console.error(`Out of date: ${target.directory}/${name}.js`); stale = true }
    else await writeFile(destination, generated)
  }
}
if (stale) process.exitCode = 1
else console.log(process.argv.includes('--check') ? 'Shared game artifacts are current.' : 'Shared game artifacts synchronized for WeChat and uniCloud.')
